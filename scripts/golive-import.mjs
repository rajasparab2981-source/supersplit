#!/usr/bin/env node
// Builds the go-live SQL that loads a v1 backup into the Mumbai project and
// imports it into the v2 schema, linking the owner's account.
//
//   node scripts/golive-import.mjs backups/live-<date> "<owner v1 name>"
//
// Writes <backup dir>/golive-import.sql (git-ignored with backups/). The
// output contains real data: never commit it. Run it with:
//   npx supabase db query --remote -f backups/live-<date>/golive-import.sql
//
// What the SQL does, in ONE transaction (all or nothing):
//   1. Empty the v2 tables (rehearsal/test data) and remove anonymous test users.
//   2. Recreate legacy_* tables with the v1 columns and load the backup.
//   3. private.import_legacy(<owner's Google account>, <owner v1 name>).
// The owner must have signed in with Google on this project beforehand.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [dir, ownerName] = process.argv.slice(2);
if (!dir || !ownerName) {
  console.error('Usage: node scripts/golive-import.mjs <backup dir> "<owner v1 name>"');
  process.exit(1);
}

const read = (t) => {
  const file = readdirSync(dir).filter((f) => f.endsWith(`-${t}.json`)).sort().pop();
  if (!file) throw new Error(`No *-${t}.json in ${dir}`);
  return JSON.parse(readFileSync(join(dir, file), 'utf8'));
};
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${(a ?? []).map(q).join(',')}]::text[]`;
const jsonb = (o) => (o && Object.keys(o).length ? `${q(JSON.stringify(o))}::jsonb` : 'null');
const num = (n) => { const x = Number(n); if (!Number.isFinite(x)) throw new Error(`Bad amount ${n}`); return String(x); };

const data = { groups: read('groups'), members: read('members'), trips: read('trips'), expenses: read('expenses') };
if (!data.members.some((m) => m.name === ownerName)) {
  throw new Error(`"${ownerName}" is not a v1 member. Members: ${data.members.map((m) => m.name).join(', ')}`);
}

const sql = [`-- Generated by scripts/golive-import.mjs. Contains real data: do not commit.
begin;
truncate public.groups, public.group_members, public.trips, public.expenses, public.expense_payers,
  public.expense_splits, public.expense_reactions, public.settlements, public.invites, public.activity_log
  restart identity cascade;
delete from auth.users where is_anonymous;
drop table if exists public.legacy_expenses, public.legacy_trips, public.legacy_members, public.legacy_groups;
create table public.legacy_groups (id uuid primary key, name text not null, emoji text not null, color text not null, created_at timestamptz);
create table public.legacy_members (id uuid primary key, group_id uuid, name text not null, created_at timestamptz);
create table public.legacy_trips (id uuid primary key, group_id uuid, name text not null, emoji text not null, created_at timestamptz);
create table public.legacy_expenses (id uuid primary key, trip_id uuid, description text not null, amount numeric(12,2) not null,
  paid_by text not null, split_among text[] not null, category text not null, expense_date date not null, created_at timestamptz,
  shares jsonb, reactions jsonb, image_url text);
alter table public.legacy_groups enable row level security;
alter table public.legacy_members enable row level security;
alter table public.legacy_trips enable row level security;
alter table public.legacy_expenses enable row level security;
revoke all on public.legacy_groups, public.legacy_members, public.legacy_trips, public.legacy_expenses from anon, authenticated;`];

for (const g of data.groups) sql.push(`insert into public.legacy_groups values (${q(g.id)},${q(g.name)},${q(g.emoji)},${q(g.color)},${q(g.created_at)});`);
for (const m of data.members) sql.push(`insert into public.legacy_members values (${q(m.id)},${q(m.group_id)},${q(m.name)},${q(m.created_at)});`);
for (const t of data.trips) sql.push(`insert into public.legacy_trips values (${q(t.id)},${q(t.group_id)},${q(t.name)},${q(t.emoji)},${q(t.created_at)});`);
for (const e of data.expenses) {
  sql.push(`insert into public.legacy_expenses values (${q(e.id)},${q(e.trip_id)},${q(e.description)},${num(e.amount)},${q(e.paid_by)},${arr(e.split_among)},${q(e.category)},${q(e.expense_date)},${q(e.created_at)},${jsonb(e.shares)},${jsonb(e.reactions)},${q(e.image_url)});`);
}
sql.push(`do $$
declare owner uuid := (select user_id from auth.identities where provider = 'google' order by created_at limit 1);
begin
  if owner is null then raise exception 'Owner has not signed in with Google on this project yet'; end if;
  perform private.import_legacy(owner, ${q(ownerName)});
  if (select count(*) from public.expenses) <> ${data.expenses.length} then
    raise exception 'Imported expense count does not match the backup (${data.expenses.length})';
  end if;
end $$;
commit;`);

const out = join(dir, 'golive-import.sql');
writeFileSync(out, sql.join('\n'));
console.log(`Wrote ${out}: ${data.groups.length} groups, ${data.members.length} members, ${data.trips.length} trips, ${data.expenses.length} expenses; owner "${ownerName}".`);
